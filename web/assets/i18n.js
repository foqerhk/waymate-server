function hostDefaultLang() {
  const host = (location.hostname || "").toLowerCase();
  if (host.endsWith(".net") || host.includes("intentcomputing.net")) return "en";
  if (host.endsWith(".cn") || host.includes("intentcomputing.cn")) return "zh";
  return null;
}

function currentLang() {
  const q = new URLSearchParams(location.search).get("lang");
  if (q === "en" || q === "zh") return q;
  const byHost = hostDefaultLang();
  if (byHost) return byHost;
  return (navigator.language || "").toLowerCase().startsWith("zh") ? "zh" : "en";
}

function applyI18n(lang) {
  const pack = I18N[lang] || I18N.zh;
  document.documentElement.lang = lang === "zh" ? "zh-Hans" : "en";
  document.documentElement.dataset.locale = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (pack[key] != null) el.textContent = pack[key];
  });
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute("content", pack.hero_lede);
  const btn = document.getElementById("langBtn");
  if (btn) btn.textContent = lang === "zh" ? "EN" : "中文";
  const titleKey = document.body && document.body.dataset.titleKey;
  const brand = lang === "zh" ? "带路 Way Mate" : "Way Mate";
  document.title = titleKey && pack[titleKey] ? `${pack[titleKey]} · ${brand}` : brand;
  document.dispatchEvent(new CustomEvent("langchange", { detail: lang }));
}

document.addEventListener("DOMContentLoaded", () => {
  let lang = currentLang();
  applyI18n(lang);
  const btn = document.getElementById("langBtn");
  if (btn) {
    btn.addEventListener("click", () => {
      lang = lang === "zh" ? "en" : "zh";
      const url = new URL(location.href);
      url.searchParams.set("lang", lang);
      history.replaceState(null, "", url);
      applyI18n(lang);
    });
  }
});
